import { normalizePlan } from "../write-plan/schemas.js";
import { validateStep } from "../write-plan/validators.js";

export function buildAnalysisWritePlanProposal({
    analyses = [],
    discipline = "general",
    context = {},
    revitVersion = "2022",
} = {}) {
    const steps = uniqueSteps(collectProposalSteps(analyses));
    const proposalErrors = collectProposalErrors(analyses);
    const validationRows = steps.map((step, index) => {
        const result = validateStep(step, index);
        return {
            stepId: step.stepId,
            operation: step.operation,
            valid: result.errors.length === 0,
            errors: result.errors,
            warnings: result.warnings,
        };
    });
    const errors = [
        ...proposalErrors,
        ...validationRows.flatMap((row) => row.errors),
    ];
    const warnings = validationRows.flatMap((row) => row.warnings);
    const plan = steps.length > 0
        ? normalizePlan({
            planId: `analysis-write-plan-${normalizeDisciplineForPlan(discipline)}`,
            title: "Analysis write-plan proposal",
            discipline: normalizeDisciplineForPlan(discipline),
            source: {
                userRequest: "Generated by analyze_mep_system from proposal-only engineering analysis.",
                createdBy: "analysis",
                revitVersion,
            },
            context: {
                documentTitle: context.documentTitle || "",
                activeViewId: context.activeViewId || 0,
                activeViewType: context.activeViewType || "",
            },
            steps,
            verification: {
                proposalOnly: true,
                requiredNextStep: "prepare_write_plan then preview_write_plan before any commit request",
            },
        })
        : null;
    return {
        success: errors.length === 0,
        method: "Aggregate proposal-only write-plan steps from engineering analysis outputs",
        stepCount: steps.length,
        operations: [...new Set(steps.map((step) => step.operation))],
        plan,
        validation: {
            valid: errors.length === 0,
            errors,
            warnings,
            rows: validationRows,
        },
        assumptions: [
            "This object is a proposal handoff only; it is not a commit approval.",
            "Generated steps must still go through prepare_write_plan, preview_write_plan, explicit approval, commit_write_plan, and verify_write_plan.",
            "Engineering standards, local-loss context, and target identities remain visible in the source analysis rows and step preconditions.",
        ],
        canCommit: false,
    };
}

export function collectProposalSteps(analyses = []) {
    const steps = [];
    for (const analysis of Array.isArray(analyses) ? analyses : []) {
        appendSteps(steps, analysis?.writePlanSteps);
        appendSteps(steps, analysis?.ductSizingProposal?.writePlanSteps);
        appendSteps(steps, analysis?.pipeSizingProposal?.writePlanSteps);
        appendSteps(steps, analysis?.placementProposal?.writePlanSteps);
        appendSteps(steps, analysis?.calculationExamples?.scheduleProposal?.writePlanSteps);
    }
    return steps;
}

export function collectProposalErrors(analyses = []) {
    const errors = [];
    for (const analysis of Array.isArray(analyses) ? analyses : []) {
        appendErrors(errors, analysis?.placementProposal?.errors);
        appendErrors(errors, analysis?.ductSizingProposal?.errors);
        appendErrors(errors, analysis?.pipeSizingProposal?.errors);
    }
    return errors;
}

function appendSteps(target, maybeSteps) {
    if (!Array.isArray(maybeSteps)) return;
    for (const step of maybeSteps) {
        if (!step || typeof step !== "object") continue;
        target.push({
            ...step,
            dependsOn: Array.isArray(step.dependsOn) ? step.dependsOn : [],
            preconditions: [
                ...(Array.isArray(step.preconditions) ? step.preconditions : []),
                "Review analysis proposal and run write-plan preview before commit.",
            ],
        });
    }
}

function appendErrors(target, maybeErrors) {
    if (!Array.isArray(maybeErrors)) return;
    for (const error of maybeErrors) {
        if (error === null || error === undefined) continue;
        target.push(String(error));
    }
}

function uniqueSteps(steps) {
    const counts = new Map();
    return steps.map((step, index) => {
        const base = step.stepId || `analysis-step-${String(index + 1).padStart(3, "0")}`;
        const count = counts.get(base) || 0;
        counts.set(base, count + 1);
        return {
            ...step,
            stepId: count === 0 ? base : `${base}-${count + 1}`,
        };
    });
}

function normalizeDisciplineForPlan(value) {
    const normalized = String(value || "general").toLowerCase().replace(/-/g, "_");
    return normalized === "all" ? "general" : normalized;
}
