function parseCli(argv) {
  if (argv.includes("--help") || argv.includes("-h")) {
    process.stdout.write(`${usage()}\n`);
    process.exit(0);
  }
  const configIndex = argv.indexOf("--config");
  if (configIndex < 0 || !argv[configIndex + 1]) {
    throw new Error("A local --config JSON file is required. Use the PowerShell wrapper for normal runs.");
  }
  return path.resolve(argv[configIndex + 1]);
}

function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function requireCondition(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function cleanStrings(value) {
  if (!Array.isArray(value)) return [];
  return [...new Set(value.map((item) => String(item ?? "").trim()).filter(Boolean))];
}

function cleanPositiveIntegers(value) {
  if (!Array.isArray(value)) return [];
  return [...new Set(value.map((item) => Number(item)).filter((item) => Number.isInteger(item) && item > 0))];
}

function nestedStringValues(value) {
  if (typeof value === "string") return [value];
  if (Array.isArray(value)) return value.flatMap((item) => nestedStringValues(item));
  if (isObject(value)) return Object.values(value).flatMap((item) => nestedStringValues(item));
  return [];
}

function finiteNumber(value, fallback) {
  const number = Number(value);
  return Number.isFinite(number) ? number : fallback;
}

function boundedInteger(value, fallback, minimum, maximum, name) {
  const number = finiteNumber(value, fallback);
  requireCondition(Number.isInteger(number) && number >= minimum && number <= maximum,
    `${name} must be an integer between ${minimum} and ${maximum}.`);
  return number;
}

function sha256(value) {
  return `sha256:${crypto.createHash("sha256").update(String(value), "utf8").digest("hex")}`;
}

function readWindowsDriveInfo(root) {
  requireCondition(process.platform === "win32",
    "Phase 1a live acceptance requires Windows drive-type verification.");
  if (driveInfoCache.has(root)) return driveInfoCache.get(root);
  const systemRoot = String(process.env.SystemRoot || "").trim();
  requireCondition(systemRoot, "SystemRoot is unavailable; local drive type cannot be verified.");
  const powershellPath = path.join(systemRoot, "System32", "WindowsPowerShell", "v1.0", "powershell.exe");
  requireCondition(fs.existsSync(powershellPath),
    "Windows PowerShell is unavailable; local drive type cannot be verified.");
  const rootBase64 = Buffer.from(root, "utf16le").toString("base64");
  const command = [
    "$ErrorActionPreference='Stop'",
    "$root=[Text.Encoding]::Unicode.GetString([Convert]::FromBase64String($env:REVAGENT_DRIVE_ROOT_B64))",
    "$drive=[IO.DriveInfo]::new($root)",
    "[ordered]@{driveType=[int]$drive.DriveType;isReady=[bool]$drive.IsReady}|ConvertTo-Json -Compress",
  ].join(";");
  let parsed;
  try {
    const output = execFileSync(powershellPath, [
      "-NoLogo",
      "-NoProfile",
      "-NonInteractive",
      "-Command",
      command,
    ], {
      encoding: "utf8",
      env: { ...process.env, REVAGENT_DRIVE_ROOT_B64: rootBase64 },
      stdio: ["ignore", "pipe", "ignore"],
      timeout: 5_000,
      windowsHide: true,
    });
    parsed = JSON.parse(output.trim());
  } catch {
    throw new Error("Local drive type could not be verified; refusing an unknown or network-backed root.");
  }
  const result = {
    driveType: Number(parsed?.driveType),
    isReady: parsed?.isReady === true,
  };
  requireCondition(Number.isInteger(result.driveType),
    "Local drive type verification returned an invalid numeric DriveType.");
  driveInfoCache.set(root, result);
  return result;
}

function assertAllowedLocalDrive(value, label, reader = readWindowsDriveInfo) {
  const root = path.parse(value).root;
  requireCondition(root, `${label} drive root could not be resolved.`);
  const drive = reader(root);
  requireCondition(drive.isReady === true && ALLOWED_LOCAL_DRIVE_TYPES.has(drive.driveType),
    `${label} must be on a ready local Fixed, Removable, or RAM drive; Network/Unknown/NoRoot roots are rejected.`);
}

function percentile95(values) {
  requireCondition(values.length > 0, "Cannot calculate p95 from an empty sample.");
  const ordered = [...values].sort((left, right) => left - right);
  return ordered[Math.max(0, Math.ceil(ordered.length * 0.95) - 1)];
}

function field(value, name) {
  if (!isObject(value)) return undefined;
  if (Object.hasOwn(value, name)) return value[name];
  const pascalName = name.charAt(0).toUpperCase() + name.slice(1);
  return value[pascalName];
}

function unwrapResult(value) {
  let current = value;
  for (let depth = 0; depth < 3; depth += 1) {
    const nested = field(current, "result");
    if (!isObject(current) || !isObject(nested)) break;
    current = nested;
  }
  return current;
}

function parseToolResult(value) {
  requireCondition(isObject(value) && Array.isArray(value.content),
    "The public capture handler returned no MCP content.");
  const textBlock = value.content.find((item) => isObject(item) && item.type === "text" && typeof item.text === "string");
  requireCondition(textBlock, "The public capture handler returned no JSON text block.");
  try {
    return JSON.parse(textBlock.text);
  } catch {
    throw new Error("The public capture handler returned invalid JSON text.");
  }
}

function readConfig(configPath) {
  requireCondition(fs.existsSync(configPath), "The local harness config file was not found.");
  let config;
  try {
    config = JSON.parse(fs.readFileSync(configPath, "utf8").replace(/^\uFEFF/, ""));
  } catch {
    throw new Error("The local harness config file is not valid JSON.");
  }
  requireCondition(isObject(config), "The local harness config root must be an object.");

  const mode = config.recheckExisting === true ? "recheck_existing" : "capture";
  const levelNames = cleanStrings(config.levelNames);
  const levelIds = cleanPositiveIntegers(config.levelIds);
  if (mode === "capture") {
    requireCondition(levelNames.length > 0 || levelIds.length > 0,
      "Phase 1a live capture requires explicit levelNames and/or levelIds.");
  }

  const sourceScope = String(config.sourceScope || "hostAndLinked");
  requireCondition(["hostOnly", "linkedOnly", "hostAndLinked"].includes(sourceScope),
    "sourceScope must be hostOnly, linkedOnly, or hostAndLinked.");
  const repeatCount = boundedInteger(config.repeatCount, DEFAULT_REPEAT_COUNT, 2, 100, "repeatCount");
  const maxElapsedMs = boundedInteger(config.maxElapsedMs, 1_800, 250, 5_000, "maxElapsedMs");
  const timeoutMs = boundedInteger(config.timeoutMs, 60_000, 2_000, 60_000, "timeoutMs");
  requireCondition(timeoutMs >= maxElapsedMs + 1_000,
    "timeoutMs must leave at least 1000 ms above maxElapsedMs.");
  requireCondition(maxElapsedMs <= 1_800,
    "Phase 1a live acceptance does not allow maxElapsedMs above 1800 ms.");

  const maxCaptureElapsedMs = boundedInteger(config.maxCaptureElapsedMs, 45_000, 1_000, 120_000, "maxCaptureElapsedMs");
  const pageP95LimitMs = boundedInteger(config.pageP95LimitMs, DEFAULT_PAGE_P95_LIMIT_MS, 1, 5_000, "pageP95LimitMs");
  const pageMaxLimitMs = boundedInteger(config.pageMaxLimitMs, DEFAULT_PAGE_MAX_LIMIT_MS, 1, 5_000, "pageMaxLimitMs");
  const captureP95LimitMs = boundedInteger(config.captureP95LimitMs, DEFAULT_CAPTURE_P95_LIMIT_MS, 1, 120_000, "captureP95LimitMs");
  const captureMaxLimitMs = boundedInteger(config.captureMaxLimitMs, DEFAULT_CAPTURE_MAX_LIMIT_MS, 1, 360_000, "captureMaxLimitMs");
  requireCondition(maxCaptureElapsedMs <= DEFAULT_CAPTURE_P95_LIMIT_MS,
    "Phase 1a live acceptance does not allow maxCaptureElapsedMs above 45000 ms.");
  requireCondition(pageP95LimitMs <= DEFAULT_PAGE_P95_LIMIT_MS,
    "Phase 1a live acceptance does not allow page p95 above 2000 ms.");
  requireCondition(pageMaxLimitMs <= DEFAULT_PAGE_MAX_LIMIT_MS,
    "Phase 1a live acceptance does not allow page max above 5000 ms.");
  requireCondition(captureP95LimitMs <= DEFAULT_CAPTURE_P95_LIMIT_MS,
    "Phase 1a live acceptance does not allow total capture p95 above 45000 ms.");
  requireCondition(captureMaxLimitMs <= DEFAULT_CAPTURE_MAX_LIMIT_MS,
    "Phase 1a live acceptance does not allow total capture max above 60000 ms.");

  const expectedPostEditLiveness = cleanStrings(config.expectedPostEditLiveness).map((item) => item.toLowerCase());
  const expectedRecheckLiveness = String(config.expectedRecheckLiveness || "unknown").toLowerCase();
  for (const value of expectedPostEditLiveness) {
    requireCondition(["stale", "unknown"].includes(value),
      "Post-edit liveness expectations must be stale or unknown; current is never an accepted post-edit outcome.");
  }
  requireCondition(["current", "stale", "unknown"].includes(expectedRecheckLiveness),
    "Expected recheck liveness must be current, stale, or unknown.");

  return {
    mode,
    target: String(config.target || "").trim() || undefined,
    host: String(config.host || process.env.REVAGENT_HOST || "localhost").trim(),
    port: boundedInteger(config.port, Number(process.env.REVAGENT_PORT) || 8080, 1, 65_535, "port"),
    levelNames,
    levelIds,
    sourceScope,
    linkInstanceIds: cleanPositiveIntegers(config.linkInstanceIds),
    linkInstanceUniqueIds: cleanStrings(config.linkInstanceUniqueIds),
    linkedSourceLevels: Array.isArray(config.linkedSourceLevels) ? config.linkedSourceLevels : [],
    linkedSourceLevelNames: cleanStrings(config.linkedSourceLevelNames),
    includeHostMep: config.includeHostMep !== false,
    includeRoomsSpaces: config.includeRoomsSpaces !== false,
    includeLinkedObstructions: config.includeLinkedObstructions !== false,
    belowLevelMm: Number.isFinite(Number(config.belowLevelMm)) ? Number(config.belowLevelMm) : undefined,
    aboveLevelMm: Number.isFinite(Number(config.aboveLevelMm)) ? Number(config.aboveLevelMm) : undefined,
    pageTargetBytes: boundedInteger(config.pageTargetBytes, DEFAULT_PAGE_TARGET_BYTES, 64 * 1024, 8 * 1024 * 1024, "pageTargetBytes"),
    maxElements: boundedInteger(config.maxElements, 25_000, 1, 25_000, "maxElements"),
    maxElapsedMs,
    maxCaptureElapsedMs,
    timeoutMs,
    repeatCount,
    pageP95LimitMs,
    pageMaxLimitMs,
    captureP95LimitMs,
    captureMaxLimitMs,
    databasePath: String(config.databasePath || "").trim(),
    evidencePath: String(config.evidencePath || "").trim(),
    pauseAfterCapture: config.pauseAfterCapture === true,
    testConcurrentEdit: config.testConcurrentEdit === true,
    requireConnectorEvidence: config.requireConnectorEvidence !== false,
    requireDoublePlacedLinkEvidence: config.requireDoublePlacedLinkEvidence !== false,
    expectedPostEditLiveness: expectedPostEditLiveness.length > 0 ? expectedPostEditLiveness : ["stale", "unknown"],
    snapshotId: String(config.snapshotId || "").trim(),
    expectedRecheckLiveness,
  };
}

function prepareDatabase(config, assertFilesystemPath = assertAllowedLocalDrive) {
  if (config.databasePath) {
    requireCondition(path.isAbsolute(config.databasePath), "databasePath must be an absolute local path.");
    requireCondition(!config.databasePath.startsWith("\\\\"), "databasePath must not be a UNC/network path.");
    const resolved = path.resolve(config.databasePath);
    const repoPrefix = `${repoRoot.toLowerCase()}${path.sep}`;
    requireCondition(!`${resolved.toLowerCase()}${path.sep}`.startsWith(repoPrefix),
      "databasePath must stay outside the Git repository.");
    assertFilesystemPath(resolved, "databasePath");
    fs.mkdirSync(path.dirname(resolved), { recursive: true });
    return { databasePath: resolved, temporaryRoot: null, mode: "explicit" };
  }
  requireCondition(config.mode !== "recheck_existing",
    "Recheck-existing mode requires an explicit local databasePath retained from a prior capture run.");
  assertFilesystemPath(path.resolve(os.tmpdir()), "temporary database root");
  const temporaryRoot = fs.mkdtempSync(path.join(os.tmpdir(), "revagent-phase1a-live-"));
  return {
    databasePath: path.join(temporaryRoot, "spatial.db"),
    temporaryRoot,
    mode: "temporary",
  };
}

function defaultEvidencePath(mode) {
  const root = process.env.LOCALAPPDATA || os.tmpdir();
  const fileName = mode === "recheck_existing"
    ? "phase1a-live-recheck-evidence-latest.json"
    : "phase1a-live-capture-evidence-latest.json";
  return path.join(root, "revAgent", "spatial", "phase1a", fileName);
}

function sanitizeEvidence(evidence, sensitiveValues) {
  const serialized = JSON.stringify(evidence, null, 2);
  const comparable = serialized.toLowerCase();
  for (const value of sensitiveValues) {
    const text = String(value || "").trim();
    if (text.length >= 4) {
      requireCondition(!comparable.includes(text.toLowerCase()), "Sanitized evidence contained a model-sensitive input.");
    }
  }
  return `${serialized}\n`;
}

function writeEvidence(evidencePath, evidence, sensitiveValues, mode, assertFilesystemPath = assertAllowedLocalDrive) {
  const candidate = evidencePath || defaultEvidencePath(mode);
  requireCondition(path.isAbsolute(candidate), "evidencePath must be an absolute local path.");
  requireCondition(!candidate.startsWith("\\\\"), "evidencePath must not be a UNC/network path.");
  const resolved = path.resolve(candidate);
  const repoPrefix = `${repoRoot.toLowerCase()}${path.sep}`;
  requireCondition(!`${resolved.toLowerCase()}${path.sep}`.startsWith(repoPrefix),
    "evidencePath must stay outside the Git repository.");
  assertFilesystemPath(resolved, "evidencePath");
  fs.mkdirSync(path.dirname(resolved), { recursive: true });
  fs.writeFileSync(resolved, sanitizeEvidence(evidence, sensitiveValues), "utf8");
  return resolved;
}

function storeEvidence(store, snapshotId, options = {}) {
  const requireComplete = options.requireComplete !== false;
  const requireConnectorEvidence = options.requireConnectorEvidence !== false;
  const requireDoublePlacedLinkEvidence = options.requireDoublePlacedLinkEvidence !== false;
  const schemaVersion = store.getSchemaVersion();
  requireCondition(schemaVersion.major === 1 && schemaVersion.minor >= 1,
    "The built runtime spatial store is not at the Phase 1a schema version.");
  requireCondition(store.isRTreeAvailable() === true,
    "SQLite R*Tree is unavailable; Phase 1a acceptance cannot continue.");
  const record = store.getSnapshotRecord(snapshotId);
  requireCondition(record, "The committed snapshot is not readable from the durable store.");
  requireCondition(record.schemaVersion === "0.2",
    "The committed store record is not SpatialSnapshot v0.2.");
  if (requireComplete) {
    requireCondition(record.complete === true && record.partial === false && record.coverageStatus === "complete",
      "The committed store record is not complete.");
  }
  requireCondition(record.sourceCount > 0 && record.sourceRevisions.length === record.sourceCount,
    "The committed store record has incomplete source revision bindings.");
  requireCondition(record.sourceRevisions.every((source) => source.changeSequenceState === "tracked" && source.trackerSessionId),
    "The committed store record has an untracked source revision.");

  const derivedCounts = isObject(record.derivedCounts) ? record.derivedCounts : {};
  const nodesByKind = isObject(derivedCounts.nodesByKind) ? derivedCounts.nodesByKind : {};
  const connectorNodeCount = Number(nodesByKind.connector || 0);
  requireCondition(Number.isInteger(connectorNodeCount) && connectorNodeCount >= 0,
    "The committed store record has invalid connector node counts.");
  if (requireConnectorEvidence) {
    requireCondition(connectorNodeCount > 0,
      "The committed frozen MEP scope contains no connector node evidence.");
  }

  const bindingsByDocument = new Map();
  for (const source of record.sourceRevisions) {
    const documentKey = String(source.documentKey || "");
    const placementId = String(source.linkInstanceUniqueId || "");
    if (!documentKey || !placementId) continue;
    if (!bindingsByDocument.has(documentKey)) {
      bindingsByDocument.set(documentKey, {
        placements: new Set(),
        documentSessionIds: new Set(),
        trackerSessionIds: new Set(),
        changeSequences: new Set(),
        loadedVersions: new Set(),
      });
    }
    const binding = bindingsByDocument.get(documentKey);
    binding.placements.add(placementId);
    binding.documentSessionIds.add(String(source.documentSessionId || ""));
    binding.trackerSessionIds.add(String(source.trackerSessionId || ""));
    binding.changeSequences.add(String(source.changeSequence ?? ""));
    binding.loadedVersions.add(String(source.loadedVersion || ""));
  }
  const doublePlacedGroups = [...bindingsByDocument.values()].filter((binding) => binding.placements.size >= 2);
  const maximumPlacementCount = doublePlacedGroups.length > 0
    ? Math.max(...doublePlacedGroups.map((binding) => binding.placements.size))
    : 0;
  const doublePlacedBindingsConsistent = doublePlacedGroups.every((binding) =>
    binding.documentSessionIds.size === 1
      && !binding.documentSessionIds.has("")
      && binding.trackerSessionIds.size === 1
      && !binding.trackerSessionIds.has("")
      && binding.changeSequences.size === 1
      && !binding.changeSequences.has("")
      && binding.loadedVersions.size === 1
      && !binding.loadedVersions.has(""));
  if (requireDoublePlacedLinkEvidence) {
    requireCondition(doublePlacedGroups.length > 0,
      "The committed frozen scope does not prove one linked document through two distinct placements.");
    requireCondition(doublePlacedBindingsConsistent,
      "Double placements of one linked document do not share one document session, tracker, sequence, and loaded version.");
  }

  const transformValidation = isObject(record.transformValidation) ? record.transformValidation : {};
  requireCondition(field(transformValidation, "allWithin0_5mm") === true,
    "The committed store record failed the 0.5 mm transform round-trip gate.");
  const maxRoundTripError = field(transformValidation, "maxRoundTripErrorMm");
  if (maxRoundTripError !== null && maxRoundTripError !== undefined) {
    requireCondition(Number.isFinite(Number(maxRoundTripError)) && Number(maxRoundTripError) <= 0.5,
      "The committed store record exceeded the 0.5 mm transform round-trip gate.");
  }

  const rtreeEntryCount = store.countRTreeEntries(snapshotId);
  requireCondition(rtreeEntryCount > 0 && rtreeEntryCount <= record.nodeCount,
    "The committed snapshot has no valid R*Tree evidence or an impossible R*Tree count.");
  const indexedNodes = store.queryIntersectingAabbs({
    minMm: [WORLD_MIN_MM, WORLD_MIN_MM, WORLD_MIN_MM],
    maxMm: [WORLD_MAX_MM, WORLD_MAX_MM, WORLD_MAX_MM],
  }, snapshotId);
  requireCondition(indexedNodes.length === rtreeEntryCount,
    "R*Tree full-extent lookup did not return every indexed snapshot node.");
  const indexedIdentityHash = sha256(indexedNodes.map((node) => node.nodeId).sort().join("\n"));

  return {
    record,
    indexedIdentityHash,
    sanitized: {
      snapshotIdSha256: sha256(snapshotId),
      schemaVersion: record.schemaVersion,
      storeSchemaVersion: schemaVersion,
      complete: record.complete,
      partial: record.partial,
      coverageStatus: record.coverageStatus,
      scanStoppedReason: record.scanStoppedReason,
      pageCount: record.pageCount,
      payloadBytes: record.payloadBytes,
      sourceCount: record.sourceCount,
      nodeCount: record.nodeCount,
      omissionCount: record.omissionCount,
      connectorEvidence: {
        required: requireConnectorEvidence,
        state: requireConnectorEvidence ? "passed" : "not_run",
        connectorNodeCount,
      },
      doublePlacedLinkEvidence: {
        required: requireDoublePlacedLinkEvidence,
        state: requireDoublePlacedLinkEvidence ? "passed" : "not_run",
        qualifyingDocumentGroupCount: doublePlacedGroups.length,
        maximumDistinctPlacementCount: maximumPlacementCount,
        sharedDocumentSessionAndRevisionBinding: doublePlacedBindingsConsistent,
      },
      rtreeEntryCount,
      indexedIdentitySha256: indexedIdentityHash,
      transformAllWithin0_5mm: true,
      maxTransformRoundTripErrorMm: maxRoundTripError ?? null,
    },
  };
}

async function waitForOperatorEdit(prompt) {
  requireCondition(process.stdin.isTTY && process.stdout.isTTY,
    "Operator-assisted edit verification requires an interactive terminal.");
  const terminal = readline.createInterface({ input: process.stdin, output: process.stdout });
  try {
    await terminal.question(prompt);
  } finally {
    terminal.close();
  }
}

