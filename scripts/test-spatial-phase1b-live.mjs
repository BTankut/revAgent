function getAllStoredNodes(store, snapshotId, maximum = 100_000) {
  const nodes = [];
  let afterNodeId = null;
  while (nodes.length < maximum) {
    const page = store.queryStoredNodes({ snapshotId, afterNodeId, limit: Math.min(1_000, maximum - nodes.length) });
    nodes.push(...page.nodes);
    if (!page.hasMore) return nodes;
    requireCondition(page.nextNodeId && page.nextNodeId !== afterNodeId,
      "Stored-node pagination did not advance.");
    afterNodeId = page.nextNodeId;
  }
  throw new Error("Live fixture exceeds the bounded 100000-node acceptance inspection limit.");
}

function validateProfile(profile, label) {
  requireCondition(isObject(profile), `${label} omitted profile.`);
  for (const key of ["shape", "diameterMm", "widthMm", "heightMm", "insulationThicknessMm"]) {
    requireCondition(Object.hasOwn(profile, key), `${label} profile omitted ${key}.`);
  }
  requireCondition(["round", "rectangular", "oval", "unknown"].includes(profile.shape),
    `${label} profile shape is invalid.`);
  for (const key of ["diameterMm", "widthMm", "heightMm"]) {
    requireCondition(profile[key] === null || (Number.isFinite(Number(profile[key])) && Number(profile[key]) > 0),
      `${label} profile ${key} is invalid.`);
  }
  requireCondition(profile.insulationThicknessMm === null
    || (Number.isFinite(Number(profile.insulationThicknessMm)) && Number(profile.insulationThicknessMm) >= 0),
  `${label} profile insulationThicknessMm is invalid.`);
}

function validateSpatialProperties(properties, label) {
  requireCondition(isObject(properties), `${label} omitted spatialProperties.`);
  for (const key of ["systemKey", "systemName", "systemClassification"]) {
    requireCondition(Object.hasOwn(properties, key), `${label} spatialProperties omitted ${key}.`);
    requireCondition(properties[key] === null || (typeof properties[key] === "string" && properties[key].trim()),
      `${label} spatialProperties ${key} is invalid.`);
  }
  requireCondition([properties.systemKey, properties.systemName, properties.systemClassification]
    .some((value) => typeof value === "string" && value.trim()),
  `${label} has no declared system evidence.`);
}

function validateFingerprints(fingerprints, label) {
  requireCondition(isObject(fingerprints)
    && fingerprints.version === "phase1b-spatial-fingerprint/1.0",
  `${label} omitted the supported fingerprint version.`);
  for (const key of ["placement", "shape", "property", "topology"]) {
    requireCondition(SHA256_PATTERN.test(String(fingerprints[key] || "")),
      `${label} fingerprint ${key} is invalid.`);
  }
}

function isSortedUniqueStrings(values) {
  return Array.isArray(values)
    && values.every((value) => typeof value === "string" && value.length > 0)
    && values.every((value, index) => index === 0 || values[index - 1] < value);
}

function validateSnapshotContract(store, record, manifestContract) {
  requireCondition(record && record.schemaVersion === "0.3" && record.complete === true
    && record.partial === false && record.coverageStatus === "complete",
  "Committed live snapshot is not a complete SpatialSnapshot v0.3 record.");
  const nodes = getAllStoredNodes(store, record.snapshotId);
  const byId = new Map(nodes.map((node) => [node.nodeId, node]));
  const checkedElements = manifestContract.supportedElementNodeIds.map((nodeId, index) => {
    const node = byId.get(nodeId);
    requireCondition(node?.nodeKind === "revit_element", `Supported element contract case ${index + 1} was not found.`);
    validateSpatialProperties(node.payload.spatialProperties, `Supported element contract case ${index + 1}`);
    validateProfile(node.payload.profile, `Supported element contract case ${index + 1}`);
    validateFingerprints(node.payload.fingerprints, `Supported element contract case ${index + 1}`);
    requireCondition(node.payload.profile.shape !== "unknown",
      `Supported element contract case ${index + 1} has unknown profile shape.`);
    return node;
  });
  const checkedConnectors = manifestContract.supportedConnectorNodeIds.map((nodeId, index) => {
    const node = byId.get(nodeId);
    requireCondition(node?.nodeKind === "connector", `Supported connector contract case ${index + 1} was not found.`);
    validateSpatialProperties(node.payload.spatialProperties, `Supported connector contract case ${index + 1}`);
    validateProfile(node.payload.profile, `Supported connector contract case ${index + 1}`);
    validateFingerprints(node.payload.fingerprints, `Supported connector contract case ${index + 1}`);
    requireCondition(Array.isArray(node.payload.connectedToNodeIds)
      && Array.isArray(node.payload.connectedOwnerNodeIds)
      && Array.isArray(node.payload.connectionRefs),
    `Supported connector contract case ${index + 1} omitted adjacency evidence.`);
    requireCondition(isSortedUniqueStrings(node.payload.connectedToNodeIds)
      && isSortedUniqueStrings(node.payload.connectedOwnerNodeIds),
    `Supported connector contract case ${index + 1} adjacency is not sorted and deduplicated.`);
    const coverage = node.payload.topologyCoverage;
    requireCondition(isObject(coverage) && coverage.basis === "revit_connector_all_refs"
      && coverage.complete === true && coverage.allRefsRead === true
      && coverage.targetMembershipValidated === false
      && Number(coverage.unresolvedConnectorCount) === 0,
    `Supported connector contract case ${index + 1} has incomplete native topology coverage.`);
    return node;
  });

  const topology = store.getSnapshotTopologyCapability(record.snapshotId);
  requireCondition(topology?.readComplete === true && topology.targetMembershipValidated === true
    && topology.ambiguousConnectorCount === 0 && topology.unresolvedPeerReferenceCount === 0,
  "Committed snapshot topology is not reciprocal, unambiguous, and membership-validated.");
  for (const [index, pair] of manifestContract.reciprocalConnectorPairs.entries()) {
    const left = byId.get(pair.leftNodeId);
    const right = byId.get(pair.rightNodeId);
    requireCondition(left?.nodeKind === "connector" && right?.nodeKind === "connector",
      `Reciprocal topology case ${index + 1} is missing connector nodes.`);
    requireCondition(left.payload.connectedToNodeIds.includes(right.nodeId)
      && right.payload.connectedToNodeIds.includes(left.nodeId),
    `Reciprocal topology case ${index + 1} is not declared in both directions.`);
    const edges = store.getAdjacentStoredEdges(record.snapshotId, left.nodeId, { limit: 2_000 });
    requireCondition(edges.some((edge) => edge.bidirectional === true
      && ((edge.sourceNodeId === left.nodeId && edge.targetNodeId === right.nodeId)
        || (edge.sourceNodeId === right.nodeId && edge.targetNodeId === left.nodeId))),
    `Reciprocal topology case ${index + 1} has no validated stored edge.`);
  }

  requireCondition(field(record.transformValidation, "allWithin0_5mm") === true,
    "Snapshot transform validation did not remain within 0.5 mm.");
  for (const [index, pair] of manifestContract.doublePlacementPairs.entries()) {
    const left = byId.get(pair.leftNodeId);
    const right = byId.get(pair.rightNodeId);
    const leftRef = left?.payload?.elementRef;
    const rightRef = right?.payload?.elementRef;
    requireCondition(left?.nodeKind === "revit_element" && right?.nodeKind === "revit_element"
      && isObject(leftRef) && isObject(rightRef),
    `Double-placement case ${index + 1} is missing element evidence.`);
    requireCondition(left.nodeId !== right.nodeId
      && left.documentKey === right.documentKey
      && leftRef.elementUniqueId === rightRef.elementUniqueId
      && left.linkInstanceUniqueId && right.linkInstanceUniqueId
      && left.linkInstanceUniqueId !== right.linkInstanceUniqueId,
    `Double-placement case ${index + 1} did not preserve placement-aware composite identity.`);
    requireCondition(left.geometryFingerprint && right.geometryFingerprint
      && left.geometryFingerprint !== right.geometryFingerprint,
    `Double-placement case ${index + 1} did not preserve distinct host geometry.`);
    const leftSource = record.sourceRevisions.find((source) => source.linkInstanceUniqueId === left.linkInstanceUniqueId);
    const rightSource = record.sourceRevisions.find((source) => source.linkInstanceUniqueId === right.linkInstanceUniqueId);
    requireCondition(leftSource && rightSource
      && leftSource.documentKey === rightSource.documentKey
      && leftSource.documentSessionId === rightSource.documentSessionId
      && leftSource.trackerSessionId === rightSource.trackerSessionId
      && leftSource.changeSequence === rightSource.changeSequence
      && leftSource.loadedVersion === rightSource.loadedVersion
      && canonicalJson(leftSource.sourceToHostTransform) !== canonicalJson(rightSource.sourceToHostTransform),
    `Double-placement case ${index + 1} did not preserve distinct host transforms.`);
  }

  return {
    nodes,
    byId,
    checkedElements,
    checkedConnectors,
    topology,
    nodeIdentitySha256: sha256(Buffer.from(nodes.map((node) => node.nodeId).sort().join("\n"), "utf8")),
  };
}

function assertStoredElementIdentity(node, expected, label) {
  const elementRef = node?.payload?.elementRef;
  requireCondition(node?.nodeKind === "revit_element" && node.nodeId === expected.nodeId
    && isObject(elementRef) && elementRef.elementUniqueId === expected.elementUniqueId,
  `${label} did not match its captured node/element unique identity.`);
  if (expected.linkInstanceUniqueId) {
    requireCondition(node.linkInstanceUniqueId === expected.linkInstanceUniqueId,
      `${label} did not match its captured link placement identity.`);
  }
  return node;
}

function finitePoint(value) {
  return Array.isArray(value) && value.length >= 3
    && value.slice(0, 3).every((item) => Number.isFinite(Number(item)))
    ? value.slice(0, 3).map(Number) : null;
}

function probePoint(node, label) {
  const geometry = node?.payload?.geometry;
  const centerlinePoints = geometry?.centerline?.points;
  if (Array.isArray(centerlinePoints) && centerlinePoints.length >= 2) {
    const first = finitePoint(centerlinePoints[0]);
    const last = finitePoint(centerlinePoints.at(-1));
    if (first && last) return first.map((value, axis) => (value + last[axis]) / 2);
  }
  const point = finitePoint(geometry?.pointLocation?.point);
  if (point) return point;
  requireCondition(false, `${label} has no captured centerline midpoint or point location.`);
}

function polygonAbsoluteArea(loop) {
  let twiceArea = 0;
  for (let index = 0; index < loop.length; index += 1) {
    const current = loop[index];
    const next = loop[(index + 1) % loop.length];
    twiceArea += current[0] * next[1] - next[0] * current[1];
  }
  return Math.abs(twiceArea / 2);
}

function pointInPolygon2d(point, loop) {
  let inside = false;
  for (let currentIndex = 0, previousIndex = loop.length - 1;
    currentIndex < loop.length; previousIndex = currentIndex, currentIndex += 1) {
    const current = loop[currentIndex];
    const previous = loop[previousIndex];
    const crosses = ((current[1] > point[1]) !== (previous[1] > point[1]))
      && (point[0] < ((previous[0] - current[0]) * (point[1] - current[1]))
        / (previous[1] - current[1]) + current[0]);
    if (crosses) inside = !inside;
  }
  return inside;
}

function connectorPoint(node, label) {
  const point = finitePoint(node?.payload?.geometry?.pointLocation?.point);
  requireCondition(point, `${label} has no measured connector origin.`);
  return point;
}

function pointDistance(first, second) {
  return Math.sqrt(first.reduce((sum, value, axis) => sum + ((value - second[axis]) ** 2), 0));
}

function validateFixtureGroundTruthSnapshot(store, record, inspection, fixtureGroundTruth) {
  const byId = inspection.byId;
  const room = assertStoredElementIdentity(byId.get(fixtureGroundTruth.roomHole.room.nodeId),
    fixtureGroundTruth.roomHole.room, "Room-hole Room");
  const holeProbe = assertStoredElementIdentity(byId.get(fixtureGroundTruth.roomHole.holeProbe.nodeId),
    fixtureGroundTruth.roomHole.holeProbe, "Room-hole probe");
  const loops = room.payload?.geometry?.boundaryLoops;
  requireCondition(Array.isArray(loops)
    && loops.length === fixtureGroundTruth.roomHole.expectedBoundaryLoopCount,
  "Room-hole Room does not have the exact declared two-loop boundary.");
  const normalizedLoops = loops.map((loop, index) => {
    requireCondition(Array.isArray(loop) && loop.length >= 3,
      `Room-hole boundary loop ${index + 1} is invalid.`);
    const points = loop.map((point) => finitePoint(point));
    requireCondition(points.every(Boolean), `Room-hole boundary loop ${index + 1} has invalid points.`);
    return points;
  }).sort((left, right) => polygonAbsoluteArea(right) - polygonAbsoluteArea(left));
  requireCondition(polygonAbsoluteArea(normalizedLoops[0]) > polygonAbsoluteArea(normalizedLoops[1])
    && polygonAbsoluteArea(normalizedLoops[1]) > 0,
  "Room-hole loops do not expose one outer loop and one smaller inner loop.");
  const holeProbePoint = probePoint(holeProbe, "Room-hole probe");
  requireCondition(pointInPolygon2d(holeProbePoint, normalizedLoops[0])
    && pointInPolygon2d(holeProbePoint, normalizedLoops[1]),
  "Room-hole probe is not geometrically inside the declared inner hole loop.");

  const disconnectedLeft = assertStoredElementIdentity(
    byId.get(fixtureGroundTruth.coincidentDisconnected.left.nodeId),
    fixtureGroundTruth.coincidentDisconnected.left, "Coincident-disconnected left element");
  const disconnectedRight = assertStoredElementIdentity(
    byId.get(fixtureGroundTruth.coincidentDisconnected.right.nodeId),
    fixtureGroundTruth.coincidentDisconnected.right, "Coincident-disconnected right element");
  const leftConnectors = inspection.nodes.filter((node) => node.nodeKind === "connector"
    && node.payload?.ownerNodeId === disconnectedLeft.nodeId);
  const rightConnectors = inspection.nodes.filter((node) => node.nodeKind === "connector"
    && node.payload?.ownerNodeId === disconnectedRight.nodeId);
  requireCondition(leftConnectors.length > 0 && rightConnectors.length > 0,
    "Coincident-disconnected elements require captured connectors on both owners.");
  let minimumConnectorCenterDeltaMm = Number.POSITIVE_INFINITY;
  for (const leftConnector of leftConnectors) {
    const leftPoint = connectorPoint(leftConnector, "Coincident-disconnected left connector");
    const adjacentEdges = store.getAdjacentStoredEdges(record.snapshotId, leftConnector.nodeId, { limit: 2_000 });
    for (const rightConnector of rightConnectors) {
      minimumConnectorCenterDeltaMm = Math.min(minimumConnectorCenterDeltaMm,
        pointDistance(leftPoint, connectorPoint(rightConnector, "Coincident-disconnected right connector")));
      requireCondition(!leftConnector.payload.connectedToNodeIds.includes(rightConnector.nodeId)
        && !rightConnector.payload.connectedToNodeIds.includes(leftConnector.nodeId)
        && !adjacentEdges.some((edge) => edge.sourceNodeId === rightConnector.nodeId
          || edge.targetNodeId === rightConnector.nodeId),
      "Coincident-disconnected elements contain a forbidden cross-owner native topology edge.");
    }
  }
  requireCondition(minimumConnectorCenterDeltaMm
    <= fixtureGroundTruth.coincidentDisconnected.maximumConnectorCenterDeltaMm,
  "Coincident-disconnected connector centers are not within the declared tolerance.");

  const rectangular = assertStoredElementIdentity(
    byId.get(fixtureGroundTruth.rectangularProfile.element.nodeId),
    fixtureGroundTruth.rectangularProfile.element, "Rectangular-profile element");
  const rectangularProfile = rectangular.payload?.profile;
  requireCondition(isObject(rectangularProfile) && rectangularProfile.shape === "rectangular"
    && Number(rectangularProfile.widthMm) > 0 && Number(rectangularProfile.heightMm) > 0,
  "Rectangular-profile element lacks captured rectangular dimensions.");
  if (fixtureGroundTruth.rectangularProfile.expectedWidthMm !== undefined) {
    requireCondition(Math.abs(Number(rectangularProfile.widthMm)
      - fixtureGroundTruth.rectangularProfile.expectedWidthMm) <= 0.001,
    "Rectangular-profile width differs from frozen ground truth.");
  }
  if (fixtureGroundTruth.rectangularProfile.expectedHeightMm !== undefined) {
    requireCondition(Math.abs(Number(rectangularProfile.heightMm)
      - fixtureGroundTruth.rectangularProfile.expectedHeightMm) <= 0.001,
    "Rectangular-profile height differs from frozen ground truth.");
  }

  const roundNodes = [fixtureGroundTruth.straightRound.first, fixtureGroundTruth.straightRound.second]
    .map((expected, index) => assertStoredElementIdentity(byId.get(expected.nodeId), expected,
      `Straight-round element ${index + 1}`));
  for (const [index, node] of roundNodes.entries()) {
    const profile = node.payload?.profile;
    requireCondition(isObject(profile) && profile.shape === "round"
      && Number(profile.diameterMm) > 0 && Number(profile.insulationThicknessMm) >= 0,
    `Straight-round element ${index + 1} lacks captured round envelope evidence.`);
  }

  return {
    bindingSha256: sha256(Buffer.from(canonicalJson(fixtureGroundTruth), "utf8")),
    roomHole: {
      boundaryLoopCount: loops.length,
      probeInsideOuterLoop: true,
      probeInsideInnerLoop: true,
    },
    coincidentDisconnected: {
      connectorCenterDeltaMm: Number(minimumConnectorCenterDeltaMm.toFixed(6)),
      crossOwnerNativeEdgeCount: 0,
    },
    rectangularProfile: {
      shape: rectangularProfile.shape,
      widthMm: Number(rectangularProfile.widthMm),
      heightMm: Number(rectangularProfile.heightMm),
    },
    straightRound: {
      exactIdentityPairBound: true,
      expectedSeparationMm: fixtureGroundTruth.straightRound.expectedSeparationMm,
      maximumAbsoluteErrorMm: fixtureGroundTruth.straightRound.maximumAbsoluteErrorMm,
    },
  };
}

function decodeXmlText(value) {
  return String(value || "")
    .replace(/&#x([0-9a-f]+);/giu, (_match, digits) => String.fromCodePoint(Number.parseInt(digits, 16)))
    .replace(/&#([0-9]+);/gu, (_match, digits) => String.fromCodePoint(Number.parseInt(digits, 10)))
    .replace(/&lt;/giu, "<")
    .replace(/&gt;/giu, ">")
    .replace(/&quot;/giu, "\"")
    .replace(/&apos;/giu, "'")
    .replace(/&amp;/giu, "&")
    .trim();
}

function xmlElementValues(xml, elementName) {
  const expression = new RegExp(`<${elementName}\\b[^>]*>([\\s\\S]*?)<\\/${elementName}>`, "giu");
  return [...String(xml || "").matchAll(expression)].map((match) => decodeXmlText(match[1]));
}

function validateInstalledRevAgentAddin(addinPath, installedPluginPath) {
  const addinBytes = fs.readFileSync(addinPath);
  const addinText = addinBytes.toString("utf8").replace(/^\uFEFF/, "");
  const addinEntries = [...addinText.matchAll(/<AddIn\b([^>]*)>([\s\S]*?)<\/AddIn>/giu)];
  requireCondition(addinEntries.length === 1,
    "Installed Revit 2022 revAgent.addin must contain exactly one AddIn entry.");
  const [, attributes, body] = addinEntries[0];
  const typeMatch = /\bType\s*=\s*(["'])(.*?)\1/iu.exec(attributes);
  requireCondition(typeMatch && decodeXmlText(typeMatch[2]).toLowerCase() === "application",
    "Installed Revit 2022 revAgent.addin entry must have Type=Application.");
  const names = xmlElementValues(body, "Name");
  const assemblies = xmlElementValues(body, "Assembly");
  const fullClassNames = xmlElementValues(body, "FullClassName");
  requireCondition(names.length === 1 && names[0].toLowerCase() === "revagent",
    "Installed Revit 2022 revAgent.addin must contain one revAgent Name value.");
  requireCondition(fullClassNames.length === 1 && fullClassNames[0] === "RevAgentPlugin.Core.Application",
    "Installed Revit 2022 revAgent.addin must contain the expected application class.");
  requireCondition(assemblies.length === 1 && assemblies[0],
    "Installed Revit 2022 revAgent.addin must contain one Assembly value.");
  const declaredAssemblyPath = path.isAbsolute(assemblies[0])
    ? path.resolve(assemblies[0])
    : path.resolve(path.dirname(addinPath), assemblies[0]);
  requireCondition(fs.existsSync(declaredAssemblyPath) && fs.statSync(declaredAssemblyPath).isFile(),
    "Installed Revit 2022 add-in assembly path does not resolve to a file.");
  const actualAssemblyPath = fs.realpathSync.native(declaredAssemblyPath);
  const expectedAssemblyPath = fs.realpathSync.native(installedPluginPath);
  requireCondition(actualAssemblyPath.toLowerCase() === expectedAssemblyPath.toLowerCase(),
    "Installed Revit 2022 add-in manifest does not load the hash-verified revAgentPlugin.dll path.");
  return {
    addinBytes,
    entryCount: addinEntries.length,
    assemblyPathSha256: sha256(Buffer.from(actualAssemblyPath.toLowerCase(), "utf8")),
  };
}

