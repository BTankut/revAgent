function parseCli(argv) {
  if (argv.includes("--help") || argv.includes("-h")) {
    process.stdout.write(`${usage()}\n`);
    process.exit(0);
  }
  const configIndex = argv.indexOf("--config");
  if (configIndex < 0 || !argv[configIndex + 1]) {
    throw new Error("A local --config JSON file is required. Use the PowerShell wrapper for normal runs.");
  }
  return path.resolve(argv[configIndex + 1]);
}

function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function requireCondition(condition, message) {
  if (!condition) throw new Error(message);
}

function field(value, name) {
  if (!isObject(value)) return undefined;
  if (Object.hasOwn(value, name)) return value[name];
  const pascalName = name.charAt(0).toUpperCase() + name.slice(1);
  return value[pascalName];
}

function cleanStrings(value) {
  if (!Array.isArray(value)) return [];
  return [...new Set(value.map((item) => String(item ?? "").trim()).filter(Boolean))];
}

function cleanPositiveIntegers(value) {
  if (!Array.isArray(value)) return [];
  return [...new Set(value.map(Number).filter((item) => Number.isInteger(item) && item > 0))];
}

function finiteNumber(value, fallback = null) {
  const number = Number(value);
  return Number.isFinite(number) ? number : fallback;
}

function boundedInteger(value, fallback, minimum, maximum, name) {
  const number = finiteNumber(value, fallback);
  requireCondition(Number.isInteger(number) && number >= minimum && number <= maximum,
    `${name} must be an integer between ${minimum} and ${maximum}.`);
  return number;
}

function sha256(value) {
  return `sha256:${crypto.createHash("sha256").update(value).digest("hex")}`;
}

function sha256Hex(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function canonicalValue(value) {
  if (Array.isArray(value)) return value.map(canonicalValue);
  if (isObject(value)) {
    return Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonicalValue(value[key])]));
  }
  return value;
}

function canonicalJson(value) {
  return JSON.stringify(canonicalValue(value));
}

function stripVolatileNormalizedFields(value) {
  if (Array.isArray(value)) return value.map(stripVolatileNormalizedFields);
  if (!isObject(value)) return value;
  return Object.fromEntries(Object.entries(value)
    .filter(([key]) => !/(?:snapshotId|revisionFingerprint|sessionId)$/i.test(key)
      && !/^(?:reportId|elapsedMs|generatedAtUtc)$/i.test(key))
    .map(([key, child]) => [key, stripVolatileNormalizedFields(child)]));
}

function assertExactNormalized(caseId, actual, expected) {
  requireCondition(canonicalJson(actual) === canonicalJson(expected),
    `Ground-truth case ${caseId} did not match its exact normalized expected result.`);
}

function percentile(values, fraction) {
  requireCondition(values.length > 0, "Cannot calculate a percentile from an empty sample.");
  const ordered = [...values].sort((left, right) => left - right);
  return ordered[Math.max(0, Math.ceil(ordered.length * fraction) - 1)];
}

function summarizeDurations(values) {
  return {
    sampleCount: values.length,
    p50Ms: Number(percentile(values, 0.50).toFixed(3)),
    p95Ms: Number(percentile(values, 0.95).toFixed(3)),
    maxMs: Number(Math.max(...values).toFixed(3)),
  };
}

function pathIsInsideRepository(value) {
  const relative = path.relative(realRepoRoot, value);
  return relative === "" || (!relative.startsWith("..") && !path.isAbsolute(relative));
}

function readWindowsDriveInfo(root) {
  requireCondition(process.platform === "win32",
    "Phase 1b live acceptance requires Windows drive-type verification.");
  if (driveInfoCache.has(root)) return driveInfoCache.get(root);
  const systemRoot = String(process.env.SystemRoot || "").trim();
  requireCondition(systemRoot, "SystemRoot is unavailable; local drive type cannot be verified.");
  const powershellPath = path.join(systemRoot, "System32", "WindowsPowerShell", "v1.0", "powershell.exe");
  requireCondition(fs.existsSync(powershellPath),
    "Windows PowerShell is unavailable; local drive type cannot be verified.");
  const rootBase64 = Buffer.from(root, "utf16le").toString("base64");
  const command = [
    "$ErrorActionPreference='Stop'",
    "$root=[Text.Encoding]::Unicode.GetString([Convert]::FromBase64String($env:REVAGENT_DRIVE_ROOT_B64))",
    "$drive=[IO.DriveInfo]::new($root)",
    "[ordered]@{driveType=[int]$drive.DriveType;isReady=[bool]$drive.IsReady}|ConvertTo-Json -Compress",
  ].join(";");
  let parsed;
  try {
    const output = execFileSync(powershellPath, [
      "-NoLogo", "-NoProfile", "-NonInteractive", "-Command", command,
    ], {
      encoding: "utf8",
      env: { ...process.env, REVAGENT_DRIVE_ROOT_B64: rootBase64 },
      stdio: ["ignore", "pipe", "ignore"],
      timeout: 5_000,
      windowsHide: true,
    });
    parsed = JSON.parse(output.trim());
  } catch {
    throw new Error("Local drive type could not be verified; refusing an unknown or network-backed root.");
  }
  const result = { driveType: Number(parsed?.driveType), isReady: parsed?.isReady === true };
  requireCondition(Number.isInteger(result.driveType), "Local drive verification returned an invalid DriveType.");
  driveInfoCache.set(root, result);
  return result;
}

function assertExplicitLocalPath(value, label, options = {}, driveReader = readWindowsDriveInfo) {
  requireCondition(typeof value === "string" && value.trim(), `${label} is required.`);
  requireCondition(path.isAbsolute(value), `${label} must be an absolute local path.`);
  requireCondition(!value.startsWith("\\\\"), `${label} must not be a UNC/network path.`);
  const requested = path.resolve(value);
  let requestedEntry = null;
  try {
    requestedEntry = fs.lstatSync(requested);
  } catch (error) {
    requireCondition(error?.code === "ENOENT", `${label} path entry could not be inspected.`);
  }
  requireCondition(requestedEntry === null || fs.existsSync(requested),
    `${label} must not be a dangling symlink or reparse-point path.`);
  const resolved = resolveExternalArtifactPath(requested, repoRoot, label, options.existingFile === true);
  const drive = driveReader(path.parse(resolved).root);
  requireCondition(drive.isReady === true && ALLOWED_LOCAL_DRIVE_TYPES.has(drive.driveType),
    `${label} must be on a ready local Fixed, Removable, or RAM drive.`);
  if (options.existingFile === true) {
    requireCondition(fs.existsSync(resolved) && fs.statSync(resolved).isFile(), `${label} file was not found.`);
  }
  return resolved;
}

function readJsonFile(filePath, label) {
  let raw;
  let parsed;
  try {
    raw = fs.readFileSync(filePath, "utf8").replace(/^\uFEFF/, "");
    parsed = JSON.parse(raw);
  } catch {
    throw new Error(`${label} is not valid JSON.`);
  }
  requireCondition(isObject(parsed), `${label} root must be an object.`);
  return { raw, parsed };
}

function validateCaseId(value, label) {
  const text = String(value || "").trim();
  requireCondition(CASE_ID_PATTERN.test(text), `${label} must be a non-sensitive stable slug.`);
  return text;
}

function validateExpectedCase(value, label) {
  requireCondition(isObject(value), `${label} must be an object.`);
  const caseId = validateCaseId(value.caseId, `${label}.caseId`);
  requireCondition(isObject(value.args), `${label}.args must be an object.`);
  requireCondition(isObject(value.expectedNormalized), `${label}.expectedNormalized must be an object.`);
  return { ...value, caseId };
}

function validateSha256Hex(value, label) {
  const text = String(value || "").trim().toLowerCase();
  requireCondition(/^[a-f0-9]{64}$/.test(text), `${label} must be 64 lowercase hex characters.`);
  return text;
}

function validateElementIdentity(value, label, options = {}) {
  requireCondition(isObject(value), `${label} must be an object.`);
  const nodeId = String(value.nodeId || "").trim();
  const elementUniqueId = String(value.elementUniqueId || "").trim();
  requireCondition(nodeId.startsWith("node:sha256:"), `${label}.nodeId must be a placement-aware node id.`);
  requireCondition(elementUniqueId.length >= 8, `${label}.elementUniqueId is required.`);
  const linkInstanceUniqueId = String(value.linkInstanceUniqueId || "").trim() || undefined;
  if (options.requireLinkPlacement === true) {
    requireCondition(linkInstanceUniqueId, `${label}.linkInstanceUniqueId is required.`);
  }
  return { nodeId, elementUniqueId, ...(linkInstanceUniqueId ? { linkInstanceUniqueId } : {}) };
}

function validateFixtureGroundTruth(value) {
  requireCondition(isObject(value), "Ground-truth manifest requires fixtureGroundTruth.");

  const roomHole = value.roomHole;
  requireCondition(isObject(roomHole), "fixtureGroundTruth.roomHole is required.");
  const expectedBoundaryLoopCount = Number(roomHole.expectedBoundaryLoopCount);
  requireCondition(expectedBoundaryLoopCount === 2,
    "fixtureGroundTruth.roomHole.expectedBoundaryLoopCount must be exactly 2.");

  const coincidentDisconnected = value.coincidentDisconnected;
  requireCondition(isObject(coincidentDisconnected),
    "fixtureGroundTruth.coincidentDisconnected is required.");
  const maximumConnectorCenterDeltaMm = Number(coincidentDisconnected.maximumConnectorCenterDeltaMm);
  requireCondition(Number.isFinite(maximumConnectorCenterDeltaMm)
    && maximumConnectorCenterDeltaMm > 0 && maximumConnectorCenterDeltaMm <= 0.1,
  "fixtureGroundTruth.coincidentDisconnected.maximumConnectorCenterDeltaMm must be within (0, 0.1].");

  const rectangularProfile = value.rectangularProfile;
  requireCondition(isObject(rectangularProfile), "fixtureGroundTruth.rectangularProfile is required.");
  const expectedWidthMm = rectangularProfile.expectedWidthMm === undefined
    ? undefined : Number(rectangularProfile.expectedWidthMm);
  const expectedHeightMm = rectangularProfile.expectedHeightMm === undefined
    ? undefined : Number(rectangularProfile.expectedHeightMm);
  requireCondition(expectedWidthMm === undefined || (Number.isFinite(expectedWidthMm) && expectedWidthMm > 0),
    "fixtureGroundTruth.rectangularProfile.expectedWidthMm must be positive when supplied.");
  requireCondition(expectedHeightMm === undefined || (Number.isFinite(expectedHeightMm) && expectedHeightMm > 0),
    "fixtureGroundTruth.rectangularProfile.expectedHeightMm must be positive when supplied.");

  const straightRound = value.straightRound;
  requireCondition(isObject(straightRound), "fixtureGroundTruth.straightRound is required.");
  const expectedSeparationMm = Number(straightRound.expectedSeparationMm);
  const maximumAbsoluteErrorMm = Number(straightRound.maximumAbsoluteErrorMm);
  requireCondition(expectedSeparationMm === 840,
    "fixtureGroundTruth.straightRound.expectedSeparationMm must be the frozen 840 mm Revit measurement.");
  requireCondition(Number.isFinite(maximumAbsoluteErrorMm)
    && maximumAbsoluteErrorMm > 0 && maximumAbsoluteErrorMm <= 1,
  "fixtureGroundTruth.straightRound.maximumAbsoluteErrorMm must be within (0, 1].");

  return {
    roomHole: {
      room: validateElementIdentity(roomHole.room, "fixtureGroundTruth.roomHole.room", { requireLinkPlacement: true }),
      holeProbe: validateElementIdentity(roomHole.holeProbe, "fixtureGroundTruth.roomHole.holeProbe"),
      expectedBoundaryLoopCount,
    },
    coincidentDisconnected: {
      left: validateElementIdentity(coincidentDisconnected.left,
        "fixtureGroundTruth.coincidentDisconnected.left"),
      right: validateElementIdentity(coincidentDisconnected.right,
        "fixtureGroundTruth.coincidentDisconnected.right"),
      maximumConnectorCenterDeltaMm,
    },
    rectangularProfile: {
      element: validateElementIdentity(rectangularProfile.element,
        "fixtureGroundTruth.rectangularProfile.element"),
      ...(expectedWidthMm !== undefined ? { expectedWidthMm } : {}),
      ...(expectedHeightMm !== undefined ? { expectedHeightMm } : {}),
    },
    straightRound: {
      first: validateElementIdentity(straightRound.first, "fixtureGroundTruth.straightRound.first"),
      second: validateElementIdentity(straightRound.second, "fixtureGroundTruth.straightRound.second"),
      expectedSeparationMm,
      maximumAbsoluteErrorMm,
    },
  };
}

function unorderedPairMatches(values, first, second) {
  return Array.isArray(values) && values.length === 2
    && new Set(values).size === 2 && values.includes(first) && values.includes(second);
}

function operationPairNodeIds(operation) {
  return [operation?.firstNodeId ?? operation?.sourceNodeId, operation?.secondNodeId ?? operation?.targetNodeId]
    .map((value) => String(value || "").trim()).filter(Boolean);
}

function assertFixtureGroundTruthCaseBindings(fixtureGroundTruth, operationCases) {
  const roomCase = operationCases.find((item) => item.goldClass === "containment"
    && item.variant === "room_hole_exclusion");
  requireCondition(roomCase?.operation?.name === "locate_in_space"
    && roomCase.operation.nodeId === fixtureGroundTruth.roomHole.holeProbe.nodeId
    && Array.isArray(roomCase.operation.spaceNodeIds)
    && roomCase.operation.spaceNodeIds.includes(fixtureGroundTruth.roomHole.room.nodeId),
  "Room-hole gold case is not structurally bound to fixtureGroundTruth.roomHole.");

  const topologyCase = operationCases.find((item) => item.goldClass === "topology"
    && item.variant === "coincident_disconnected");
  requireCondition(topologyCase?.operation?.name === "trace_connectivity"
    && unorderedPairMatches([
      topologyCase.operation.startNodeId,
      topologyCase.operation.targetNodeId,
    ], fixtureGroundTruth.coincidentDisconnected.left.nodeId,
    fixtureGroundTruth.coincidentDisconnected.right.nodeId),
  "Coincident-disconnected gold case is not structurally bound to its declared elements.");

  const rectangularCase = operationCases.find((item) =>
    item.groundTruth?.profileClass === "rectangular_screening_only");
  requireCondition(rectangularCase
    && operationPairNodeIds(rectangularCase.operation)
      .includes(fixtureGroundTruth.rectangularProfile.element.nodeId),
  "Rectangular screening case is not structurally bound to fixtureGroundTruth.rectangularProfile.");

  const roundCase = operationCases.find((item) =>
    item.groundTruth?.profileClass === "straight_round_to_round"
    && unorderedPairMatches(operationPairNodeIds(item.operation),
      fixtureGroundTruth.straightRound.first.nodeId,
      fixtureGroundTruth.straightRound.second.nodeId));
  requireCondition(roundCase
    && Number(roundCase.groundTruth.revitMeasuredExpectedDistanceMm)
      === fixtureGroundTruth.straightRound.expectedSeparationMm,
  "Straight-round measured case is not structurally bound to the declared 840 mm pair.");
}

function readConfig(configPath) {
  const { parsed } = readJsonFile(configPath, "Harness config");
  const levelNames = cleanStrings(parsed.levelNames);
  const levelIds = cleanPositiveIntegers(parsed.levelIds);
  requireCondition(levelNames.length > 0 || levelIds.length > 0,
    "Phase 1b live acceptance requires explicit levelNames and/or levelIds.");
  const sourceScope = String(parsed.sourceScope || "hostAndLinked");
  requireCondition(["hostOnly", "linkedOnly", "hostAndLinked"].includes(sourceScope),
    "sourceScope must be hostOnly, linkedOnly, or hostAndLinked.");
  const repeatCount = boundedInteger(parsed.repeatCount, 20, 20, 100, "repeatCount");
  const operationLimitMs = boundedInteger(parsed.operationLimitMs, 750, 1, 750, "operationLimitMs");
  const diffLimitMs = boundedInteger(parsed.diffLimitMs, 3_000, 1, 3_000, "diffLimitMs");
  const maxElapsedMs = boundedInteger(parsed.maxElapsedMs, 1_800, 250, 1_800, "maxElapsedMs");
  const timeoutMs = boundedInteger(parsed.timeoutMs, 60_000, 2_000, 120_000, "timeoutMs");
  requireCondition(timeoutMs >= maxElapsedMs + 1_000,
    "timeoutMs must leave at least 1000 ms above maxElapsedMs.");
  const target = String(parsed.target || "tcp").trim().toLowerCase();
  const host = String(parsed.host || process.env.REVAGENT_HOST || "localhost").trim().toLowerCase();
  const port = boundedInteger(parsed.port, Number(process.env.REVAGENT_PORT) || 8080, 1, 65_535, "port");
  requireCondition(target === "tcp" && LOCKED_GATE_D_HOSTS.has(host) && port === 8080,
    "Phase 1b Gate D endpoint must be tcp localhost/127.0.0.1 port 8080.");
  return {
    target,
    host,
    port,
    levelNames,
    levelIds,
    linkedSourceLevels: Array.isArray(parsed.linkedSourceLevels) ? parsed.linkedSourceLevels : [],
    linkedSourceLevelNames: cleanStrings(parsed.linkedSourceLevelNames),
    sourceScope,
    linkInstanceIds: cleanPositiveIntegers(parsed.linkInstanceIds),
    linkInstanceUniqueIds: cleanStrings(parsed.linkInstanceUniqueIds),
    includeHostMep: parsed.includeHostMep !== false,
    includeRoomsSpaces: parsed.includeRoomsSpaces !== false,
    includeLinkedObstructions: parsed.includeLinkedObstructions !== false,
    belowLevelMm: Number.isFinite(Number(parsed.belowLevelMm)) ? Number(parsed.belowLevelMm) : undefined,
    aboveLevelMm: Number.isFinite(Number(parsed.aboveLevelMm)) ? Number(parsed.aboveLevelMm) : undefined,
    pageTargetBytes: boundedInteger(parsed.pageTargetBytes, 262_144, 65_536, 8_388_608, "pageTargetBytes"),
    maxElements: boundedInteger(parsed.maxElements, 25_000, 1, 25_000, "maxElements"),
    maxElapsedMs,
    maxCaptureElapsedMs: boundedInteger(parsed.maxCaptureElapsedMs, 45_000, 1_000, 120_000, "maxCaptureElapsedMs"),
    timeoutMs,
    repeatCount,
    operationLimitMs,
    diffLimitMs,
    fixturePath: assertExplicitLocalPath(String(parsed.fixturePath || ""), "fixturePath", { existingFile: true }),
    databasePath: assertExplicitLocalPath(String(parsed.databasePath || ""), "databasePath", { existingFile: true }),
    evidencePath: assertExplicitLocalPath(String(parsed.evidencePath || ""), "evidencePath"),
    groundTruthManifestPath: assertExplicitLocalPath(
      String(parsed.groundTruthManifestPath || ""),
      "groundTruthManifestPath",
      { existingFile: true },
    ),
    agentEvalEvidencePath: assertExplicitLocalPath(
      String(parsed.agentEvalEvidencePath || ""),
      "agentEvalEvidencePath",
      { existingFile: true },
    ),
  };
}

function readGroundTruthManifest(manifestPath, agentEvalEvidencePath, fixturePath, databasePath) {
  const { raw, parsed } = readJsonFile(manifestPath, "Ground-truth manifest");
  requireCondition(parsed.schemaVersion === MANIFEST_SCHEMA,
    `Ground-truth manifest schemaVersion must be ${MANIFEST_SCHEMA}.`);
  requireCondition(parsed.operatorApproved === true && parsed.fixtureFrozen === true,
    "Ground-truth manifest must be operator-approved and declare a frozen/disposable fixture.");
  const fixtureFileSha256 = validateSha256Hex(parsed.fixtureFileSha256,
    "Ground-truth manifest fixtureFileSha256");
  const agentEvalEvidenceSha256 = validateSha256Hex(parsed.agentEvalEvidenceSha256,
    "Ground-truth manifest agentEvalEvidenceSha256");
  const fixtureGroundTruth = validateFixtureGroundTruth(parsed.fixtureGroundTruth);

  const contract = parsed.contractCases;
  requireCondition(isObject(contract), "Ground-truth manifest requires contractCases.");
  const supportedElementNodeIds = cleanStrings(contract.supportedElementNodeIds);
  const supportedConnectorNodeIds = cleanStrings(contract.supportedConnectorNodeIds);
  requireCondition(supportedElementNodeIds.length >= 2,
    "contractCases requires at least two declared supported element nodes.");
  requireCondition(supportedConnectorNodeIds.length >= 2,
    "contractCases requires declared connector nodes.");
  const reciprocalConnectorPairs = Array.isArray(contract.reciprocalConnectorPairs)
    ? contract.reciprocalConnectorPairs : [];
  const doublePlacementPairs = Array.isArray(contract.doublePlacementPairs) ? contract.doublePlacementPairs : [];
  requireCondition(reciprocalConnectorPairs.length > 0,
    "contractCases requires at least one reciprocal connector pair.");
  requireCondition(doublePlacementPairs.length > 0,
    "contractCases requires at least one same-source double-placement pair.");
  for (const [index, pair] of reciprocalConnectorPairs.entries()) {
    requireCondition(isObject(pair) && typeof pair.leftNodeId === "string" && typeof pair.rightNodeId === "string",
      `reciprocalConnectorPairs[${index}] is invalid.`);
  }
  for (const [index, pair] of doublePlacementPairs.entries()) {
    requireCondition(isObject(pair) && typeof pair.leftNodeId === "string" && typeof pair.rightNodeId === "string",
      `doublePlacementPairs[${index}] is invalid.`);
  }

  const operationCases = Array.isArray(parsed.operationCases) ? parsed.operationCases.map((item, index) => {
    const value = validateExpectedCase({ ...item, args: item?.operation }, `operationCases[${index}]`);
    const operationName = String(value.operation?.name || "");
    requireCondition(REQUIRED_OPERATION_NAMES.includes(operationName),
      `operationCases[${index}] has an unsupported operation name.`);
    requireCondition(["containment", "direction", "topology", "distance", "other"].includes(value.goldClass),
      `operationCases[${index}].goldClass is invalid.`);
    requireCondition(typeof value.variant === "string" && value.variant.trim(),
      `operationCases[${index}].variant is required.`);
    return value;
  }) : [];
  const operationNames = new Set(operationCases.map((item) => item.operation.name));
  for (const name of REQUIRED_OPERATION_NAMES) {
    requireCondition(operationNames.has(name), `operationCases must include ${name}.`);
  }
  requireCondition(operationCases.some((item) => item.goldClass === "containment" && item.variant === "room_hole_exclusion"),
    "operationCases must include the Room-hole exclusion gold case.");
  requireCondition(operationCases.some((item) => item.goldClass === "direction"),
    "operationCases must include a direction gold case.");
  requireCondition(operationCases.some((item) => item.goldClass === "topology" && item.variant === "coincident_disconnected"),
    "operationCases must include coincident-but-disconnected topology evidence.");
  const measuredRoundCases = operationCases.filter((item) =>
    item.groundTruth?.profileClass === "straight_round_to_round");
  requireCondition(measuredRoundCases.length > 0,
    "At least one straight_round_to_round Revit-measured ground-truth case is required.");
  for (const item of measuredRoundCases) {
    requireCondition(Number.isFinite(Number(item.groundTruth.revitMeasuredExpectedDistanceMm)),
      `Ground-truth case ${item.caseId} requires revitMeasuredExpectedDistanceMm.`);
    requireCondition(item.operation.name === "relation_between" || item.operation.name === "clearance_between",
      `Ground-truth case ${item.caseId} must use a supported pair-distance operation.`);
  }
  requireCondition(operationCases.some((item) => item.groundTruth?.profileClass === "rectangular_screening_only"),
    "At least one rectangular_screening_only case is required.");
  assertFixtureGroundTruthCaseBindings(fixtureGroundTruth, operationCases);

  const retrieveCase = validateExpectedCase(parsed.retrieveCase, "retrieveCase");
  const summaryCase = validateExpectedCase(parsed.summaryCase, "summaryCase");
  const diffCase = validateExpectedCase(parsed.diffCase, "diffCase");
  const baseSnapshotAlias = validateCaseId(diffCase.baseSnapshotAlias,
    "diffCase.baseSnapshotAlias");
  const headSnapshotAlias = validateCaseId(diffCase.headSnapshotAlias,
    "diffCase.headSnapshotAlias");
  requireCondition(baseSnapshotAlias !== headSnapshotAlias,
    "diffCase baseSnapshotAlias/headSnapshotAlias must be distinct.");
  requireCondition(!Object.hasOwn(diffCase.args, "baseSnapshotId")
    && !Object.hasOwn(diffCase.args, "headSnapshotId"),
  "diffCase.args must not bypass alias binding with raw snapshot ids.");
  diffCase.baseSnapshotAlias = baseSnapshotAlias;
  diffCase.headSnapshotAlias = headSnapshotAlias;

  const snapshotAliases = isObject(parsed.snapshotAliases) ? parsed.snapshotAliases : {};
  for (const [alias, snapshotId] of Object.entries(snapshotAliases)) {
    validateCaseId(alias, "snapshotAliases key");
    requireCondition(typeof snapshotId === "string" && snapshotId.trim(),
      `snapshotAliases.${alias} must contain a retained snapshot id.`);
  }
  for (const alias of [baseSnapshotAlias, headSnapshotAlias]) {
    requireCondition(alias === "base" || alias === "head" || typeof snapshotAliases[alias] === "string",
      `diffCase snapshot alias ${alias} is not base, head, or a retained snapshotAliases key.`);
  }

  const failClosedCases = Array.isArray(parsed.failClosedCases) ? parsed.failClosedCases.map((item, index) => {
    requireCondition(isObject(item), `failClosedCases[${index}] must be an object.`);
    const caseId = validateCaseId(item.caseId, `failClosedCases[${index}].caseId`);
    requireCondition(REQUIRED_FAIL_CLOSED_CLASSES.includes(item.failureClass),
      `failClosedCases[${index}].failureClass is invalid.`);
    requireCondition(["query_spatial_context", "compare_spatial_snapshots", "summarize_spatial_state"].includes(item.tool),
      `failClosedCases[${index}].tool is invalid.`);
    requireCondition(isObject(item.args), `failClosedCases[${index}].args must be an object.`);
    requireCondition(typeof item.expectedReason === "string" && item.expectedReason.trim(),
      `failClosedCases[${index}].expectedReason is required.`);
    if (["stale", "unknown", "unsupported", "ambiguous"].includes(item.failureClass)) {
      requireCondition(item.tool === "query_spatial_context",
        `failClosedCases[${index}] must exercise query_spatial_context for ${item.failureClass}.`);
    }
    if (item.failureClass === "incompatible") {
      requireCondition(item.tool === "compare_spatial_snapshots",
        `failClosedCases[${index}] must exercise compare_spatial_snapshots for incompatible inputs.`);
    }
    return { ...item, caseId };
  }) : [];
  const failureClasses = new Set(failClosedCases.map((item) => item.failureClass));
  for (const failureClass of REQUIRED_FAIL_CLOSED_CLASSES) {
    requireCondition(failureClasses.has(failureClass),
      `failClosedCases must include ${failureClass}.`);
  }

  requireCondition(parsed.agentEvalResults === undefined,
    "Inline agentEvalResults are not accepted; use the hash-bound external agent eval evidence file.");
  const evalContractPath = path.join(repoRoot, "evals", "evals.json");
  const evalContractRaw = fs.readFileSync(evalContractPath, "utf8").replace(/^\uFEFF/, "");
  const evalContract = JSON.parse(evalContractRaw);
  const requiredAgentEvalVariants = requiredPhase1bAgentEvals(evalContract);
  requireCondition(requiredAgentEvalVariants.length === 11,
    "Repository agent eval contract must contain exactly 11 required Phase 1b variants.");
  const evalContractSha256 = sha256(Buffer.from(evalContractRaw, "utf8"));
  const runtimePackage = JSON.parse(fs.readFileSync(path.join(runtimeRoot, "package.json"), "utf8"));
  const runtimeReleasePath = path.join(runtimeRoot, "release", "index.js");
  const agentEvalEvidence = validateAgentEvalEvidenceFile(agentEvalEvidencePath, {
    repoRoot,
    expectedFileSha256: agentEvalEvidenceSha256,
    fixturePath,
    databasePath,
    fixtureFileSha256: `sha256:${fixtureFileSha256}`,
    evalContractSha256,
    evalDocument: evalContract,
    requiredEvals: requiredAgentEvalVariants,
    runtimePackageVersion: String(runtimePackage.version || ""),
    runtimeReleaseSha256: sha256(fs.readFileSync(runtimeReleasePath)),
    runtimeBuildTreeSha256: computeRuntimeBuildTreeSha256(runtimeRoot),
  });

  return {
    rawSha256: sha256(Buffer.from(raw, "utf8")),
    fixtureFileSha256,
    agentEvalEvidenceSha256: `sha256:${agentEvalEvidenceSha256}`,
    fixtureGroundTruth,
    contract: {
      supportedElementNodeIds,
      supportedConnectorNodeIds,
      reciprocalConnectorPairs,
      doublePlacementPairs,
    },
    operationCases,
    measuredRoundCases,
    retrieveCase,
    summaryCase,
    diffCase,
    snapshotAliases,
    failClosedCases,
    agentEvalEvidence,
    requiredAgentEvalVariants,
    evalContractSha256,
  };
}

