function assertFailClosed(result, failCase) {
  requireCondition(result.success === true && result.guarded === true && result.state === "guarded"
    && result.reason === failCase.expectedReason,
  `Fail-closed case ${failCase.caseId} did not return its exact guarded reason.`);
  requireCondition(!Object.hasOwn(result, "computed") && !Object.hasOwn(result, "nodes")
    && !Object.hasOwn(result, "edges") && result.verdictCapability === undefined,
  `Fail-closed case ${failCase.caseId} exposed deterministic result evidence.`);
  requireCondition(result.liveness !== "current", `Fail-closed case ${failCase.caseId} claimed current liveness.`);
  assertNoForbiddenClaims(result, `Fail-closed case ${failCase.caseId}`);
  const warnings = nestedStrings(result.warnings).join("\n");
  if (failCase.failureClass === "stale" || failCase.failureClass === "unknown") {
    requireCondition(result.reason === "snapshot_not_current"
      && warnings.includes(`snapshot_liveness_${failCase.failureClass}`),
    `Fail-closed case ${failCase.caseId} did not preserve ${failCase.failureClass} liveness evidence.`);
  }
  if (failCase.failureClass === "partial") {
    requireCondition(result.reason === "incomplete_snapshot", `Fail-closed case ${failCase.caseId} did not reject partial evidence.`);
  }
  if (failCase.failureClass === "unsupported") {
    requireCondition(/unsupported|node_not_found_or_geometry_unsupported/.test(result.reason),
      `Fail-closed case ${failCase.caseId} did not expose unsupported evidence.`);
  }
  if (failCase.failureClass === "ambiguous") {
    requireCondition(/ambiguous|topology/.test(result.reason),
      `Fail-closed case ${failCase.caseId} did not reject ambiguous evidence.`);
  }
  if (failCase.failureClass === "incompatible") {
    requireCondition(/incomparable|mismatch/.test(result.reason),
      `Fail-closed case ${failCase.caseId} did not reject incompatible evidence.`);
  }
}

