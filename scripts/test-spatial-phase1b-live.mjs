function resolveSnapshotAliases(value, aliases) {
  if (typeof value === "string") {
    if (value === "$base") return aliases.base;
    if (value === "$head" || value === "$current") return aliases.head;
    if (value.startsWith("$snapshot:")) {
      const alias = value.slice("$snapshot:".length);
      requireCondition(typeof aliases.named[alias] === "string", `Unknown retained snapshot alias: ${alias}.`);
      return aliases.named[alias];
    }
    return value;
  }
  if (Array.isArray(value)) return value.map((item) => resolveSnapshotAliases(item, aliases));
  if (isObject(value)) {
    return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, resolveSnapshotAliases(child, aliases)]));
  }
  return value;
}

function resolveSnapshotAliasRecord(store, alias, aliases) {
  const snapshotId = alias === "base" ? aliases.base
    : alias === "head" ? aliases.head : aliases.named[alias];
  requireCondition(typeof snapshotId === "string" && snapshotId.trim(),
    `Snapshot alias ${alias} has no retained snapshot id.`);
  const record = store.getSnapshotRecord(snapshotId);
  requireCondition(record, `Snapshot alias ${alias} points to a missing retained snapshot.`);
  return record;
}

