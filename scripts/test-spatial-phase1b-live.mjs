function validateAgentEvalExecutionBinding(store, agentEvidence, referenceRecord, liveRuntimeIdentity, config) {
  const expectedEndpoint = {
    target: config.target || "tcp",
    host: String(config.host || "localhost").toLowerCase(),
    port: Number(config.port),
  };
  requireCondition(expectedEndpoint.target === "tcp"
      && ["localhost", "127.0.0.1"].includes(expectedEndpoint.host)
      && expectedEndpoint.port === 8080,
  "Gate D agent evidence requires the live harness endpoint to be tcp localhost/127.0.0.1 port 8080.");
  requireCondition(agentEvidence.endpoint?.target === "tcp"
      && ["localhost", "127.0.0.1"].includes(String(agentEvidence.endpoint?.host).toLowerCase())
      && Number(agentEvidence.endpoint?.port) === 8080,
  "Agent evidence endpoint is not the locked local Phase 1b endpoint.");
  requireCondition(agentEvidence.databasePathSha256
      === sha256(Buffer.from(fs.realpathSync.native(config.databasePath), "utf8")),
  "Agent evidence was not collected from the live Gate D acceptance database path.");
  requireCondition(canonicalJson(runtimeIdentityCore(liveRuntimeIdentity))
      === canonicalJson(agentEvidence.runtimeIdentity),
  "Agent evidence runtime identity does not match the live Gate D status preflight.");
  const referenceSourceBinding = referenceRecord.captureMetadata?.sourceBindingFingerprint;
  requireCondition(typeof referenceSourceBinding === "string" && referenceSourceBinding,
    "Live reference snapshot lacks sourceBindingFingerprint.");
  for (const binding of agentEvidence.snapshotBindings) {
    const record = store.getSnapshotRecord(binding.snapshotId);
    requireCondition(record, `Agent evidence snapshot ${binding.snapshotId} is absent from the retained Gate D database.`);
    requireCondition(record.documentKey === binding.documentKey
        && record.scopeFingerprint === binding.scopeFingerprint
        && record.captureMetadata?.sourceBindingFingerprint === binding.sourceBindingFingerprint
        && record.revisionFingerprint === binding.revisionFingerprint
        && record.complete === binding.complete
        && record.partial === binding.partial
        && (record.coverageStatus ?? null) === binding.coverageStatus,
    `Agent evidence snapshot ${binding.snapshotId} no longer matches its stored document/scope/source/revision binding.`);
    requireCondition(binding.documentKey === referenceRecord.documentKey
        && binding.scopeFingerprint === referenceRecord.scopeFingerprint
        && binding.sourceBindingFingerprint === referenceSourceBinding,
    `Agent evidence snapshot ${binding.snapshotId} is not from the frozen fixture document/scope/source family.`);
  }
  return {
    passed: true,
    endpoint: "tcp://localhost:8080",
    snapshotBindingCount: agentEvidence.snapshotBindings.length,
    documentKeySha256: sha256(Buffer.from(referenceRecord.documentKey, "utf8")),
    scopeFingerprintSha256: sha256(Buffer.from(referenceRecord.scopeFingerprint, "utf8")),
    sourceBindingFingerprintSha256: sha256(Buffer.from(referenceSourceBinding, "utf8")),
    runtimeIdentitySha256: sha256(Buffer.from(canonicalJson(agentEvidence.runtimeIdentity), "utf8")),
  };
}

function nestedStrings(value) {
  if (typeof value === "string") return [value];
  if (Array.isArray(value)) return value.flatMap(nestedStrings);
  if (isObject(value)) return Object.values(value).flatMap(nestedStrings);
  return [];
}

function assertNoForbiddenClaims(value, label) {
  const forbiddenKeys = new Set(["live_verdict", "clashFree", "clearanceVerified"]);
  const forbiddenValues = new Set(["live_verdict", "clearance_verified", "clash_free", "no_clashes", "clearance_verdict"]);
  const forbiddenPhrases = [
    /\bclearance (?:is )?verified\b/i,
    /\bclash[- ]free\b/i,
    /\b(?:there (?:is|are) )?no clashes?\b/i,
  ];
  function visit(current) {
    if (Array.isArray(current)) {
      current.forEach(visit);
      return;
    }
    if (isObject(current)) {
      for (const [key, child] of Object.entries(current)) {
        requireCondition(!forbiddenKeys.has(key), `${label} emitted a forbidden verification field.`);
        if (key === "clearanceVerdict") {
          requireCondition(child === null || child === undefined,
            `${label} emitted a non-null clearance verdict.`);
        }
        visit(child);
      }
      return;
    }
    if (typeof current === "string") {
      requireCondition(!forbiddenValues.has(current.toLowerCase())
        && !forbiddenPhrases.some((pattern) => pattern.test(current)),
      `${label} emitted a forbidden live-verdict claim.`);
    }
  }
  visit(value);
}

function withoutUndefined(value) {
  if (Array.isArray(value)) return value.map(withoutUndefined);
  if (isObject(value)) {
    return Object.fromEntries(Object.entries(value)
      .filter(([, child]) => child !== undefined)
      .map(([key, child]) => [key, withoutUndefined(child)]));
  }
  return value;
}

