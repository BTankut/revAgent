function sanitizeEvidence(evidence, sensitiveValues) {
  const serialized = JSON.stringify(evidence, null, 2);
  const comparable = serialized.toLowerCase();
  for (const value of sensitiveValues) {
    const text = String(value || "").trim();
    if (text.length >= 4) {
      requireCondition(!comparable.includes(text.toLowerCase()),
        "Sanitized evidence contained a fixture-sensitive identity or local path.");
    }
  }
  const forbiddenEvidenceKeys = new Set(["elementId", "connectorId", "coordinates", "roomData", "rawSnapshot", "prompt"]);
  function inspectKeys(value) {
    if (Array.isArray(value)) return value.forEach(inspectKeys);
    if (!isObject(value)) return;
    for (const [key, child] of Object.entries(value)) {
      requireCondition(!forbiddenEvidenceKeys.has(key), "Sanitized evidence contained a prohibited detailed-evidence field.");
      inspectKeys(child);
    }
  }
  inspectKeys(evidence);
  return `${serialized}\n`;
}

function writeSanitizedEvidence(config, evidence, sensitiveValues, runtimeFilesystemGuard) {
  runtimeFilesystemGuard(config.evidencePath, "evidencePath");
  fs.mkdirSync(path.dirname(config.evidencePath), { recursive: true });
  fs.writeFileSync(config.evidencePath, sanitizeEvidence(evidence, sensitiveValues), "utf8");
}

